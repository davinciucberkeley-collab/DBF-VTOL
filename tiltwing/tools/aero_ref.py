"""Independent aero reference for the dashboard: AeroSandbox AeroBuildup on the same geometry.

Builds the tilt-wing as an asb.Airplane (S1223 wing, NACA 0009 tail with elevator, fuselage from the same profile),
tilts wing and tail about their spars, and sweeps alpha in the paper's wing coordinates (alpha measured from the wing
chord, paper §4) at 20 m/s, sea level - the paper's CFD condition. No propellers or slipstream (as the paper's CFD).
Writes tiltwing/data/aero.json. Run: python3 tiltwing/tools/aero_ref.py
"""
import json, os, subprocess, math
import numpy as np
import aerosandbox as asb

HERE = os.path.dirname(os.path.abspath(__file__)); TW = os.path.dirname(HERE)
js = """const M=require(process.argv[1]+'/model.js');M.setAirfoils(require(process.argv[1]+'/data/airfoils.json'));
const p=Object.assign(M.defaults(), require(process.argv[2]));const r=M.size(p);delete r.in;console.log(JSON.stringify({p,r}));"""
D = json.loads(subprocess.check_output(["node", "-e", js, TW, os.path.join(TW, "cad", "params.json")], text=True)); p, r = D["p"], D["r"]
s1223, n0009 = asb.Airfoil("s1223"), asb.Airfoil("naca0009")

def surface(name, af, half, x_le_root, cr, ct, sweep, z0, x_axis, tilt, y_in, symmetric=True, cs=None):
    t = math.tan(math.radians(sweep)); c, s_ = math.cos(math.radians(tilt)), math.sin(math.radians(tilt))
    xs = []
    for y in (y_in, half):
        x_le, ch = x_le_root + y * t, cr - (cr - ct) * y / half
        dx = x_le - x_axis                       # LE ahead of the axis is negative
        xs.append(asb.WingXSec(xyz_le=[x_axis + dx * c, y, z0 - dx * s_], chord=ch, twist=tilt, airfoil=af,
                               control_surfaces=[cs] if cs else []))
    return asb.Wing(name=name, symmetric=symmetric, xsecs=xs)

def airplane(tilt, de=0.0):
    zw, zt = 0.42 * p["df"], 0.12 * p["df"]; xth = r["xt"] - 0.3 * r["crh"]
    wing = surface("Wing", s1223, p["span"] / 2, r["xLEroot"], r["cr"], r["ct"], r["sweepLE"], zw, r["xw"], tilt, 0.0)
    elev = asb.ControlSurface(name="elevator", symmetric=True, deflection=de, hinge_point=0.75)
    tail = surface("HTail", n0009, r["bh"] / 2, xth, r["crh"], r["cth"], 5.0, zt, r["xt"], tilt, 0.0, cs=elev)
    xsf = []
    for i in range(41):
        tt = i / 40
        rr = (p["df"] / 2) * (math.sqrt(max(0, 1 - ((0.32 - tt) / 0.32) ** 2)) if tt < 0.32 else 1 if tt < 0.58 else 1 - 0.72 * ((tt - 0.58) / 0.42) ** 1.3)
        xsf.append(asb.FuselageXSec(xyz_c=[tt * p["Lf"], 0, 0], radius=max(rr, 1e-3)))
    return asb.Airplane(name="TiltWing", xyz_ref=[r["xcg"], 0, 0], s_ref=r["S"], c_ref=r["MAC"], b_ref=p["span"],
                        wings=[wing, tail], fuselages=[asb.Fuselage(name="Fuselage", xsecs=xsf)])

alphas = np.arange(-15, 21, 1.0)
out = {"source": "AeroSandbox 4.2.10 AeroBuildup, generated by tiltwing/tools/aero_ref.py", "V": 20, "alpha_wing": alphas.tolist(),
       "params": {k: p[k] for k in ("span", "AR", "taper", "Lf", "df", "Vh", "hcg")}, "tilt": {}, "elevator": {}}
for tilt in (0, 15, 30, 45, 60, 75, 90):
    ap = airplane(tilt)
    op = asb.OperatingPoint(velocity=20, alpha=alphas - tilt)        # body alpha = wing alpha - tilt
    a = asb.AeroBuildup(airplane=ap, op_point=op).run()
    out["tilt"][str(tilt)] = {k: [round(float(v), 4) for v in np.atleast_1d(a[k])] for k in ("CL", "CD", "Cm")}
    print("tilt", tilt, "CL@0 %.3f CD@0 %.3f Cm@0 %.3f" % (a["CL"][15], a["CD"][15], a["Cm"][15]))
for de in (-20, 0, 20):
    ap = airplane(0, de)
    a = asb.AeroBuildup(airplane=ap, op_point=asb.OperatingPoint(velocity=20, alpha=alphas)).run()
    out["elevator"][str(de)] = {k: [round(float(v), 4) for v in np.atleast_1d(a[k])] for k in ("CL", "CD", "Cm")}
    print("de", de, "Cm@0 %.3f" % a["Cm"][15])
json.dump(out, open(os.path.join(TW, "data", "aero.json"), "w"))
