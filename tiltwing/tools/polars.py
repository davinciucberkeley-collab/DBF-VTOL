"""Airfoil geometry + 2D polars for the tilt-wing dashboard.
Source: AeroSandbox 4.2.10 airfoil database (UIUC coordinates) and NeuralFoil (xxxlarge model).
Writes tiltwing/data/airfoils.json. Run: python3 tiltwing/tools/polars.py"""
import json, numpy as np, aerosandbox as asb
out = {"source": "AeroSandbox 4.2.10 (UIUC coords) + NeuralFoil xxxlarge, generated by tiltwing/tools/polars.py", "airfoils": {}}
alphas = np.arange(-15, 21, 1.0)
for name, res in [("s1223", [1e5, 2.5e5, 5e5, 8e5]), ("naca0009", [1e5, 2.5e5, 5e5])]:
    af = asb.Airfoil(name).repanel(n_points_per_side=40)
    pol = {}
    for Re in res:
        a = af.get_aero_from_neuralfoil(alpha=alphas, Re=Re, mach=0.05, model_size="xxxlarge")
        pol[str(int(Re))] = {k: [round(float(v), 5) for v in a[k]] for k in ("CL", "CD", "CM")}
        pol[str(int(Re))]["confidence"] = [round(float(v), 3) for v in a["analysis_confidence"]]
    out["airfoils"][name] = {"coords": [[round(float(x), 5), round(float(y), 5)] for x, y in af.coordinates],
                             "alpha": alphas.tolist(), "polars": pol}
    for Re, p in pol.items():
        cl = np.array(p["CL"]); i = int(np.argmax(cl))
        print(name, Re, "clmax %.3f @ %+.0f deg, cl0 %.3f, cd@0 %.4f, cm@0 %.3f" % (cl[i], alphas[i], cl[15], p["CD"][15], p["CM"][15]))
json.dump(out, open("/home/claude/dbf-vtol/tiltwing/data/airfoils.json", "w"))
