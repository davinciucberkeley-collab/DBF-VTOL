// Writes docs/purchasing/C0_BOM.csv: the C0 bill of materials grouped by vendor, for ordering.
// Run after analysis/sizing.mjs:  node analysis/export_bom.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
const R = JSON.parse(readFileSync(new URL('./results.json', import.meta.url)));
const b = R.concepts.C0.bom;
// vendor from the cited source (domain in the src field) or the research-file section it came from
const VENDOR_BY_TAG = { 'BL A3': 'SunnySky USA', 'BL A2': 'SunnySky USA', 'BL ESCs': 'Amazon', 'PB 1c': 'APC Propellers', 'BA §6': 'EMAX USA',
  'BA §2': 'RaceDayQuads', 'BA §4': 'RaceDayQuads', 'BA §5': 'RadioMaster', 'BA §3': 'Holybro (ships CN)', 'BE §1': 'Amazon', 'BE §2': 'Amazon',
  'BE §3': 'Amazon', 'BE §4': 'Amazon', 'BF §1': 'OnlineMetals', 'BF §2': 'Home Depot', 'BF §3': 'Amazon', 'BF §5': 'Amazon', 'BL': 'SunnySky USA' };
function vendor(l) {
  const dom = (l.src.match(/([a-z0-9-]+\.(?:com|net|org))/i) || [])[1];
  if (/harbor freight/i.test(l.item)) return 'Harbor Freight';
  const NAMES = { 'amazon.com':'Amazon', 'emax-usa.com':'EMAX USA', 'holybro.com':'Holybro (ships CN)', 'homedepot.com':'Home Depot', 'onlinemetals.com':'OnlineMetals',
    'racedayquads.com':'RaceDayQuads', 'radiomasterrc.com':'RadioMaster', 'readymaderc.com':'ReadyMadeRC', 'sunnyskyusa.com':'SunnySky USA', 'apcprop.com':'APC Propellers', 'boltdepot.com':'Bolt Depot' };
  if (/(amazon.com)/.test(l.item)) return 'Amazon';
  if (dom) return NAMES[dom.toLowerCase()] || dom;
  const tag = Object.keys(VENDOR_BY_TAG).sort((x, y) => y.length - x.length).find(t => l.src.startsWith(t));
  return tag ? VENDOR_BY_TAG[tag] : '—';
}
const q = v => '"' + String(v).replace(/"/g, '""') + '"';
const rows = b.lines.map(l => ({ vendor: vendor(l), ...l })).sort((x, y) => x.vendor.localeCompare(y.vendor) || x.cat.localeCompare(y.cat));
const out = [['Vendor', 'Category', 'Item', 'Qty', 'Unit USD', 'Ext USD', 'Source (research file §)', 'Note', 'Ordered (Y/N)', 'Order date', 'Actual USD'].map(q).join(',')];
for (const r of rows) out.push([r.vendor, r.cat, r.item, r.qty, r.unit.toFixed(2), r.ext.toFixed(2), r.src, r.note || '', '', '', ''].map(q).join(','));
out.push('');
out.push([q('Goods subtotal'), '', '', '', '', b.goods.toFixed(2)].join(','));
out.push([q('Sales/use tax 10.25 % (Berkeley, CDTFA 2026-10-01)'), '', '', '', '', b.tax.toFixed(2)].join(','));
out.push([q('Shipping allowance (estimate)'), '', '', '', '', b.shipping.toFixed(2)].join(','));
out.push([q('Committed spend'), '', '', '', '', b.total.toFixed(2)].join(','));
out.push([q('Crash reserve left under $2,000'), '', '', '', '', b.crash.toFixed(2)].join(','));
out.push('');
for (const f of b.fees || []) out.push([q('Fee outside the hardware cap: ' + f.item), '', '', '', '', f.usd.toFixed(2)].join(','));
out.push(q('Prices checked 2026-10-13; re-check before ordering. Generated by analysis/export_bom.mjs from analysis/results.json.'));
mkdirSync(new URL('../docs/purchasing/', import.meta.url), { recursive: true });
writeFileSync(new URL('../docs/purchasing/C0_BOM.csv', import.meta.url), out.join('\r\n') + '\r\n');
const byVendor = {}; rows.forEach(r => byVendor[r.vendor] = (byVendor[r.vendor] || 0) + r.ext);
console.log('wrote docs/purchasing/C0_BOM.csv', rows.length, 'lines'); console.log(byVendor);
